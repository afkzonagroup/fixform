/** "14 days" in a language, using the runtime's CLDR plural rules. */
export function formatDays(days: number, language: Language): string {
  const forms = DAY_WORDS[language];
  const category = new Intl.PluralRules(language).select(days);
  return `${String(days)}\u00a0${forms[category] ?? forms.other}`;
}

/** Fills `{name}` placeholders. Values are inserted as plain text; callers escape for their output format. */
export function interpolate(template: string, values: Readonly<Record<string, string>>): string {
  return template.replace(/\{([a-zA-Z]+)\}/gu, (whole, name: string) => (Object.hasOwn(values, name) ? (values[name] ?? whole) : whole));
}
